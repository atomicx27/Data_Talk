"""Pydantic Data Models for the Ontology & Knowledge Framework (OKF).

The OKF is the structured, deterministic half of Data_Talk's Two-Tier Memory:
- Tables & Statistical Column Profiles (with PII flags & table roles: FACT / DIMENSION / BRIDGE)
- User-Approved & Inferred Join Relationships
- Semantic Measures & Calculated Columns (storing paired DAX + SQL expressions)
- Business Knowledge Rules & Interview Questions
- Pinned Dashboard Widgets & What-If Parameters
"""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Any

from pydantic import BaseModel, Field


class TableRole(str, Enum):
    FACT = "FACT"
    DIMENSION = "DIMENSION"
    BRIDGE = "BRIDGE"
    UNKNOWN = "UNKNOWN"


class JoinCardinality(str, Enum):
    MANY_TO_ONE = "N:1"
    ONE_TO_MANY = "1:N"
    ONE_TO_ONE = "1:1"
    MANY_TO_MANY = "N:M"


class JoinStatus(str, Enum):
    APPROVED = "approved"
    PENDING = "pending"
    REJECTED = "rejected"


class ColumnProfile(BaseModel):
    """Schema & statistical profile for a single column in a table."""

    name: str
    data_type: str
    business_alias: str = ""
    description: str = ""
    is_primary_key: bool = False
    is_foreign_key: bool = False
    is_nullable: bool = True
    is_pii: bool = False
    is_blocked: bool = False
    null_ratio: float = 0.0
    distinct_count: int = 0
    min_value: str | None = None
    max_value: str | None = None
    sample_values: list[str] = Field(default_factory=list)
    value_meanings: dict[str, str] = Field(
        default_factory=dict,
        description="Maps cryptic codes like {'C': 'Completed', 'X': 'Cancelled'}",
    )


class TableSchema(BaseModel):
    """Metadata and statistical profile for a table in the data source."""

    name: str
    business_name: str = ""
    description: str = ""
    table_role: TableRole = TableRole.UNKNOWN
    row_count: int = 0
    is_blocked: bool = False
    columns: list[ColumnProfile] = Field(default_factory=list)
    quality_alerts: list[str] = Field(default_factory=list)
    source_id: str = "default"
    source_name: str = ""

    def get_column(self, col_name: str) -> ColumnProfile | None:
        col_lower = col_name.lower()
        for col in self.columns:
            if col.name.lower() == col_lower:
                return col
        return None


class RelationshipEdge(BaseModel):
    """Represents a join relationship between two tables in the OKF graph."""

    id: str
    source_table: str
    source_column: str
    target_table: str
    target_column: str
    cardinality: JoinCardinality = JoinCardinality.MANY_TO_ONE
    join_type: str = "LEFT"
    confidence: float = 1.0
    discovery_method: str = "explicit_fk"  # explicit_fk | powerbi_dmv | lexical_overlap | user_defined
    status: JoinStatus = JoinStatus.PENDING
    overlap_ratio: float = 0.0
    is_cross_source: bool = False
    source_source_id: str = ""
    target_source_id: str = ""


class CalculatedColumn(BaseModel):
    """Row-level calculated column attached to a specific table (like Power BI Calculated Columns)."""

    id: str
    table_name: str
    name: str
    description: str = ""
    data_type: str = "DOUBLE"
    dax_expression: str = ""
    sql_expression: str = ""
    verified: bool = False
    sample_preview: list[Any] = Field(default_factory=list)


class SemanticMeasure(BaseModel):
    """Aggregation-level business metric (like Power BI DAX Measures) with dual DAX + SQL support."""

    id: str
    name: str
    table_name: str = "Metrics"
    description: str = ""
    format_string: str = "#,##0.00"
    user_input_type: str = "dax"  # dax | sql | natural_language
    dax_expression: str
    sql_expression: str
    involved_tables: list[str] = Field(default_factory=list)
    verified: bool = False
    sample_value: Any = None
    synonyms: list[str] = Field(default_factory=list)


class BusinessRule(BaseModel):
    """Captured domain knowledge from the AI Business Interview or in-chat Just-in-Time learning."""

    id: str
    category: str = "domain_logic"  # status_code | metric_definition | fiscal_calendar | filter_rule | glossary
    term: str
    definition: str
    applies_to_tables: list[str] = Field(default_factory=list)
    sql_filter_hint: str = ""
    dax_filter_hint: str = ""
    source: str = "interview"  # interview | chat_correction | manual


class InterviewQuestion(BaseModel):
    """Prioritized ambiguity question generated by the Smart Business Interviewer."""

    id: str
    priority: int = 1  # 1 = highest impact
    category: str      # cryptic_column | status_codes | date_grain | metric_definition | join_confirm
    table_name: str = ""
    column_name: str = ""
    question_text: str
    context_hint: str = ""
    suggested_options: list[str] = Field(default_factory=list)
    answer: str = ""
    answered: bool = False
    source_id: str = "default"


class WhatIfParameter(BaseModel):
    """Power BI-style What-If numeric slider parameter for scenario analysis."""

    id: str
    name: str
    description: str = ""
    min_val: float = -0.50
    max_val: float = 0.50
    step: float = 0.05
    default_val: float = 0.0
    format_as_percent: bool = True


class PinnedWidget(BaseModel):
    """Chart or KPI card pinned from Talk-to-Data Chat onto the Live Dashboard Canvas."""

    id: str
    title: str
    user_question: str
    executed_query: str
    query_dialect: str = "sql"
    chart_type: str = "bar"
    x_col: str | None = None
    y_cols: list[str] = Field(default_factory=list)
    color_col: str | None = None
    pinned_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class DataSourceConfig(BaseModel):
    """Configuration for an attached data source / database within the workspace."""

    id: str
    name: str = ""
    source_type: str = "sql"  # sql | duckdb | powerbi_pbix | powerbi_desktop | powerbi_cloud
    dialect: str = "duckdb"
    credential_ref: str = ""
    connection_metadata: dict[str, Any] = Field(default_factory=dict)
    table_names: list[str] = Field(default_factory=list)
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class OKFWorkspace(BaseModel):
    """Root Ontology & Knowledge Framework (OKF) document persisted to okf.yaml."""

    okf_version: str = "1.0"
    workspace_id: str
    workspace_name: str
    source_type: str = "duckdb"  # duckdb | sql | powerbi_pbix | powerbi_desktop | powerbi_cloud
    dialect: str = "duckdb"
    credential_ref: str = ""     # Symbolic reference only; NEVER stores raw password/secret
    connection_metadata: dict[str, Any] = Field(default_factory=dict)
    data_sources: list[DataSourceConfig] = Field(default_factory=list)
    tables: list[TableSchema] = Field(default_factory=list)
    relationships: list[RelationshipEdge] = Field(default_factory=list)
    calculated_columns: list[CalculatedColumn] = Field(default_factory=list)
    measures: list[SemanticMeasure] = Field(default_factory=list)
    business_rules: list[BusinessRule] = Field(default_factory=list)
    interview_questions: list[InterviewQuestion] = Field(default_factory=list)
    what_if_parameters: list[WhatIfParameter] = Field(default_factory=list)
    pinned_widgets: list[PinnedWidget] = Field(default_factory=list)
    updated_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    def get_table(self, table_name: str) -> TableSchema | None:
        t_lower = table_name.lower()
        for tbl in self.tables:
            if tbl.name.lower() == t_lower and not tbl.is_blocked:
                return tbl
        return None

    def active_tables(self) -> list[TableSchema]:
        return [t for t in self.tables if not t.is_blocked]

    def approved_relationships(self) -> list[RelationshipEdge]:
        return [r for r in self.relationships if r.status == JoinStatus.APPROVED]

    def blocked_table_names(self) -> set[str]:
        return {t.name for t in self.tables if t.is_blocked}

    def blocked_column_names(self) -> set[str]:
        cols: set[str] = set()
        for t in self.tables:
            for c in t.columns:
                if c.is_blocked:
                    cols.add(c.name)
                    cols.add(f"{t.name}.{c.name}")
        return cols

    def get_source(self, source_id: str) -> DataSourceConfig | None:
        for s in self.data_sources:
            if s.id == source_id:
                return s
        return None

    def tables_by_source(self, source_id: str) -> list[TableSchema]:
        return [t for t in self.tables if t.source_id == source_id]

    def questions_by_source(self, source_id: str) -> list[InterviewQuestion]:
        return [q for q in self.interview_questions if q.source_id == source_id]
